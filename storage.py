"""CRM storage. Supports local SQLite and hosted PostgreSQL; never stores API keys."""
import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
from urllib.parse import urlparse
from database import PostgresConnection, hosted_url

DB_PATH = Path(__file__).resolve().parent / "data" / "leads.sqlite3"


def connect(path: str | Path | None = None):
    url = hosted_url() if path is None else ''
    if url:
        conn = PostgresConnection(url)
    else:
        target = Path(path or DB_PATH)
        target.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(str(target))
        conn.row_factory = sqlite3.Row
        conn.execute('PRAGMA foreign_keys=ON')
    primary_key = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if url else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    conn.execute(f"""CREATE TABLE IF NOT EXISTS prospects (
        id {primary_key},
        website TEXT NOT NULL UNIQUE,
        canonical_domain TEXT UNIQUE,
        name TEXT NOT NULL,
        country TEXT NOT NULL DEFAULT '',
        score INTEGER NOT NULL DEFAULT 0,
        status TEXT NOT NULL DEFAULT '未联系',
        email TEXT NOT NULL DEFAULT '',
        contact_name TEXT NOT NULL DEFAULT '',
        research_json TEXT NOT NULL DEFAULT '{{}}',
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
    )""")
    conn.execute(f"""CREATE TABLE IF NOT EXISTS drafts (
        id {primary_key},
        prospect_id INTEGER NOT NULL,
        stage INTEGER NOT NULL,
        subject TEXT NOT NULL,
        body TEXT NOT NULL,
        created_at TEXT NOT NULL,
        FOREIGN KEY(prospect_id) REFERENCES prospects(id)
    )""")
    columns = {row['name'] if isinstance(row, sqlite3.Row) else row['column_name'] for row in
               (conn.execute('PRAGMA table_info(prospects)').fetchall() if not url else
                conn.execute("SELECT column_name FROM information_schema.columns WHERE table_name='prospects'").fetchall())}
    if 'canonical_domain' not in columns:
        conn.execute('ALTER TABLE prospects ADD COLUMN canonical_domain TEXT')
    # Keep the earliest record and its drafts when old full-URL keys overlap.
    rows = conn.execute('SELECT id,website,canonical_domain FROM prospects ORDER BY CASE WHEN canonical_domain IS NULL THEN 1 ELSE 0 END,id').fetchall()
    domains = {}
    for row in rows:
        domain = canonical_domain(row['website'])
        if not domain:
            continue
        if domain in domains:
            conn.execute('UPDATE drafts SET prospect_id=? WHERE prospect_id=?', (domains[domain], row['id']))
            conn.execute('DELETE FROM prospects WHERE id=?', (row['id'],))
        else:
            domains[domain] = row['id']
            if row['canonical_domain'] != domain:
                conn.execute('UPDATE prospects SET canonical_domain=? WHERE id=?', (domain, row['id']))
    conn.execute('CREATE UNIQUE INDEX IF NOT EXISTS prospects_domain_unique ON prospects(canonical_domain)')
    conn.commit()
    return conn


def canonical_domain(website: str) -> str:
    value = str(website or '').strip()
    parsed = urlparse(value if '://' in value else 'https://' + value)
    host = (parsed.hostname or '').lower().rstrip('.')
    if host.startswith('www.'):
        host = host[4:]
    if not host or '.' not in host or any(c.isspace() for c in host):
        raise ValueError('请输入有效的公司域名')
    return host


def upsert_prospect(conn: sqlite3.Connection, data: dict[str, Any], *, commit: bool = True) -> int:
    website = str(data.get("input_website") or data.get("website") or "").strip()
    domain = canonical_domain(website)
    name = str(data.get("company_name") or data.get("name") or website).strip()
    now = datetime.now(timezone.utc).isoformat()
    existing = conn.execute('SELECT id FROM prospects WHERE canonical_domain=? OR website=?', (domain, website)).fetchone()
    if existing:
        pid = existing['id']
        conn.execute('''UPDATE prospects SET name=?,country=?,score=?,research_json=?,updated_at=?,canonical_domain=? WHERE id=?''',
                     (name, str(data.get('country') or ''), int(data.get('score') or 0),
                      json.dumps(data, ensure_ascii=False), now, domain, pid))
    else:
        conn.execute('''INSERT INTO prospects (website,canonical_domain,name,country,score,research_json,created_at,updated_at)
                        VALUES (?,?,?,?,?,?,?,?)''',
                     (website, domain, name, str(data.get('country') or ''), int(data.get('score') or 0),
                      json.dumps(data, ensure_ascii=False), now, now))
        pid = conn.execute('SELECT id FROM prospects WHERE canonical_domain=?', (domain,)).fetchone()['id']
    if commit:
        conn.commit()
    return pid


def list_prospects(conn: sqlite3.Connection) -> list[dict[str, Any]]:
    return [dict(x) for x in conn.execute("SELECT * FROM prospects ORDER BY updated_at DESC").fetchall()]


def get_prospect(conn: sqlite3.Connection, prospect_id: int) -> dict[str, Any] | None:
    r = conn.execute("SELECT * FROM prospects WHERE id=?", (prospect_id,)).fetchone()
    return dict(r) if r else None


def update_details(conn: sqlite3.Connection, pid: int, status: str, email: str, contact_name: str) -> None:
    now = datetime.now(timezone.utc).isoformat()
    conn.execute("UPDATE prospects SET status=?,email=?,contact_name=?,updated_at=? WHERE id=?", (status, email, contact_name, now, pid))
    conn.commit()


def save_draft(conn: sqlite3.Connection, pid: int, stage: int, draft: dict[str, str], *, commit: bool = True):
    now = datetime.now(timezone.utc).isoformat()
    conn.execute("INSERT INTO drafts (prospect_id,stage,subject,body,created_at) VALUES (?,?,?,?,?)", (pid, stage, draft["subject"], draft["body"], now))
    if commit:
        conn.commit()


def list_drafts(conn: sqlite3.Connection, pid: int) -> list[dict[str, Any]]:
    return [dict(r) for r in conn.execute("SELECT * FROM drafts WHERE prospect_id=? ORDER BY created_at DESC", (pid,))]
